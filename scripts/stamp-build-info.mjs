// Writes the version and commit of an image build into the application
// (src/app/core/build-info/build-info.ts). Run by the Dockerfile before `ng build`; a local
// build never runs it and keeps the committed "0.0.0-dev" values.
//
//   APP_VERSION=0.1.0 GIT_COMMIT=<sha> node scripts/stamp-build-info.mjs
import { writeFileSync } from 'node:fs';

const TARGET = new URL('../src/app/core/build-info/build-info.ts', import.meta.url);

// the values end up in source code, so only what a tag or a sha can look like is let through
const version = /^[0-9A-Za-z][0-9A-Za-z.+_-]{0,63}$/.test(process.env.APP_VERSION ?? '')
  ? process.env.APP_VERSION
  : '0.0.0-dev';
const commit = /^[0-9a-f]{7,40}$/.test(process.env.GIT_COMMIT ?? '')
  ? process.env.GIT_COMMIT.slice(0, 12)
  : 'unknown';

writeFileSync(
  TARGET,
  `export interface BuildInfo {
  readonly version: string;
  readonly commit: string;
  /** ISO instant of the build; empty for a local build. */
  readonly builtAt: string;
}

// Generated by scripts/stamp-build-info.mjs during the image build.
export const BUILD_INFO: BuildInfo = {
  version: ${JSON.stringify(version)},
  commit: ${JSON.stringify(commit)},
  builtAt: ${JSON.stringify(new Date().toISOString())},
};
`,
);

console.log(`build info stamped: version ${version}, commit ${commit}`);
